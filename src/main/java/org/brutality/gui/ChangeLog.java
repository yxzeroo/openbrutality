    public static List<ChangeLog.Entry> computeList(int n) {
        ArrayList list = new ArrayList();

        for (int i = 0; i < Math.min(n, entries.size()); i++) {
            list.add(entries.get(i));
        }

        return list;
    }

    public static String computeString(int n) {
        ChangeLog.Entry entry = computeEntry();
        if (entry == null) {
            return "No changes available";
        }
        StringBuilder sb = new StringBuilder();

        for (int i = 0; i < entry.entries.size(); i++) {
            if (i > 0) {
                sb.append(", ");
            }

            sb.append(entry.entries.get(i));
            if (sb.length() > n - 3) {
                sb.setLength(n - 3);
                sb.append("...");
                break;
            }
        }

        return sb.toString();
    }

    public static class Entry {
        public final String text;
        public final String text2;
        public final String text3;
        public final List<String> entries;
        public final ChangeLog.ReleaseMode releaseMode;

        public Entry(String text, String str, ChangeLog.ReleaseMode releaseMode, String str2, List<String> list) {
            this.text = text;
            this.text2 = str;
            this.text3 = str2;
            this.releaseMode = releaseMode;
            this.entries = new ArrayList<>(list);
        }

        public Entry(String text, String str, ChangeLog.ReleaseMode releaseMode, String str2, String... parts) {
            this.text = text;
            this.text2 = str;
            this.text3 = str2;
            this.releaseMode = releaseMode;
            this.entries = Arrays.asList(parts);
        }

        public int computeInt() {
            int n = 0;

            for (String str : this.entries) {
                if (str.equals("RELEASE INFO")) {
                    break;
                }

                if (!ChangeLog.matchesString(str)) {
                    n++;
                }
            }

            return n;
        }
    }

